package mcpserver

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"
)

type schemaView struct {
	Type       any                        `json:"type"`
	Required   []string                   `json:"required"`
	Properties map[string]json.RawMessage `json:"properties"`
}

type propView struct {
	Type        any    `json:"type"`
	Description string `json:"description"`
}

func typeName(t any) string {
	switch v := t.(type) {
	case string:
		return v
	case []any:
		var parts []string
		for _, p := range v {
			if s, ok := p.(string); ok && s != "null" {
				parts = append(parts, s)
			}
		}
		return strings.Join(parts, " or ")
	}
	return "object"
}

func decodeSchema(v any) schemaView {
	var s schemaView
	if b, err := json.Marshal(v); err == nil {
		_ = json.Unmarshal(b, &s)
	}
	return s
}

func writeProps(b *strings.Builder, s schemaView, withDesc bool) {
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	if len(names) == 0 {
		b.WriteString("None.\n\n")
		return
	}
	if withDesc {
		b.WriteString("| Field | Type | Required | Description |\n|---|---|---|---|\n")
	} else {
		b.WriteString("| Field | Type |\n|---|---|\n")
	}
	for _, n := range names {
		var p propView
		_ = json.Unmarshal(s.Properties[n], &p)
		if withDesc {
			yes := "no"
			if req[n] {
				yes = "yes"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", n, typeName(p.Type), yes, p.Description)
		} else {
			fmt.Fprintf(b, "| `%s` | %s |\n", n, typeName(p.Type))
		}
	}
	b.WriteString("\n")
}

// RenderContract renders docs/contracts/mcp-tools.md from the tool list the
// server advertises, so the document cannot drift from the code.
func RenderContract(tools []*mcp.Tool) string {
	sorted := append([]*mcp.Tool(nil), tools...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	var b strings.Builder
	b.WriteString("# MCP tools contract (v1)\n\n")
	b.WriteString("<!-- Generated by `go test ./internal/mcpserver -update` from the tool list. Do not edit by hand. -->\n\n")
	b.WriteString("`stkr mcp` is a Model Context Protocol server over stdio. Server name `stkr`; the version is the STKR version. It offers the tools below, the resource `" + ManifestURI + "` (markdown) and the prompts `start_day` and `close_day`.\n\n")
	b.WriteString("## Conventions\n\n")
	b.WriteString("- Every tool returns a one-line text summary plus structured JSON (`structuredContent`) that matches the output fields below. Durations are integer seconds in `*_seconds` fields; times are RFC 3339 with the configured zone offset.\n")
	b.WriteString("- Errors are MCP tool errors (`isError: true`) whose text starts with a code: `[invalid]`, `[not_found]`, `[conflict]`, `[unavailable]` or `[internal]` (details are in the STKR log). A request that breaks the input schema is rejected as a protocol error before the tool runs.\n")
	b.WriteString("- Limits: text fields up to 10 KB (short fields 500 bytes), `limit` 1 to 200 (default 50). Time events are recorded with source `mcp`.\n")
	b.WriteString("- Privacy: personal ideas, items of personal and system projects and the notes of personal and system time are never returned. No tool returns configuration, paths or secrets.\n")
	b.WriteString("- Changes within v1 are additive: new optional inputs and new output fields.\n\n")
	b.WriteString("## Tools\n\n")
	for _, t := range sorted {
		fmt.Fprintf(&b, "### `%s`\n\n%s\n\n", t.Name, t.Description)
		kind := "changes data"
		if t.Annotations != nil && t.Annotations.ReadOnlyHint {
			kind = "read only"
		}
		fmt.Fprintf(&b, "Access: %s.\n\nInput:\n\n", kind)
		writeProps(&b, decodeSchema(t.InputSchema), true)
		b.WriteString("Output (top-level fields):\n\n")
		writeProps(&b, decodeSchema(t.OutputSchema), false)
	}
	b.WriteString("## Example\n\nRequest:\n\n```json\n{\"jsonrpc\":\"2.0\",\"id\":3,\"method\":\"tools/call\",\"params\":{\"name\":\"switch_context\",\"arguments\":{\"context\":\"planning\",\"note\":\"morning plan\"}}}\n```\n\n")
	b.WriteString("Result (shortened):\n\n```json\n{\"content\":[{\"type\":\"text\",\"text\":\"Now tracking planning\"}],\"structuredContent\":{\"event\":{\"id\":7,\"context_id\":\"planning\",\"source\":\"mcp\"},\"created\":true}}\n```\n\n")
	b.WriteString("Error result:\n\n```json\n{\"isError\":true,\"content\":[{\"type\":\"text\",\"text\":\"[not_found] context \\\"nope\\\" not found\"}]}\n```\n")
	return b.String()
}
